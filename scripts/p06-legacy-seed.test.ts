import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const f=JSON.parse(readFileSync(new URL('../data/d7-legacy-media-seed.json',import.meta.url),'utf8'));
const SHA=/^[a-f0-9]{64}$/;
assert.equal(f.schema,'zevanory-d7-legacy-media-seed/v1');
assert.equal(f.record_count,368);
assert.equal(f.unique_count,349);
assert.equal(f.unique_media_sha256.length,349);
assert.ok(f.unique_media_sha256.every((s:string)=>SHA.test(s)));
assert.equal(new Set(f.unique_media_sha256).size,349);
assert.deepEqual([...f.unique_media_sha256].sort(),f.unique_media_sha256);
assert.ok(SHA.test(f.manifest_sha256)&&SHA.test(f.zip_sha256));
assert.equal(f.duplicate_groups.length,11);
const allRecords=f.duplicate_groups.flatMap((g:any)=>g.record_numbers);
assert.equal(allRecords.length,30,'exactly 30 records in duplicate groups');
assert.equal(new Set(allRecords).size,30,'no index belongs to two groups');
assert.equal(f.record_count-f.unique_count,19,'19 extra copies');
assert.ok(f.duplicate_groups.every((g:any)=>SHA.test(g.sha256)&&g.count===g.record_numbers.length&&g.count>1));
assert.ok(f.duplicate_groups.every((g:any)=>f.unique_media_sha256.includes(g.sha256)));
const six=f.duplicate_groups.find((g:any)=>g.count===6);
assert.deepEqual(six?.record_numbers,[35,46,201,240,293,340],'real six-time group');
const archived001='d70dfaa87334a48b1aec6bc4fc560724bed4ef48694e15491ed8aee123f721c2';
assert.ok(f.unique_media_sha256.includes(archived001),'real historical record 001 SHA is in seed');
const ledger=new Set(f.unique_media_sha256);
function reserveIfNovel(hash:string){if(ledger.has(hash))return 'p06_duplicate_media_sha256';ledger.add(hash);return 'reserved';}
assert.equal(reserveIfNovel(archived001),'p06_duplicate_media_sha256');
for(const group of f.duplicate_groups)assert.equal(reserveIfNovel(group.sha256),'p06_duplicate_media_sha256','legacy duplicated image MUST be rejected');
assert.equal(reserveIfNovel('f'.repeat(64)),'reserved','novel media may reserve');
